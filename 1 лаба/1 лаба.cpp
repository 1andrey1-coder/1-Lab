
//

#include <iostream>
#include <stdio.h>
#include <math.h>

int main() {
    // 1. Объявление вещественных переменных и задание значений
    double a = 1.0, b = -3.0, c = 2.0; // Пример: x^2 - 3x + 2 = 0
    double D, x1, x2;

    printf("Уравнение: %.2lfx^2 + %.2lfx + %.2lf = 0\n", a, b, c);

    // Проверка, является ли уравнение квадратным
    if (a == 0) {
        printf("Это не квадратное уравнение (a=0).\n");
        return 0;
    }

    // 2. Вычисление дискриминанта D = b^2 - 4ac
    D = pow(b, 2) - 4 * a * c;
    printf("Дискриминант D = %.2lf\n", D);


    // 3. Условная конструкция для D>0, D=0, D<0
    if (D > 0) {
        // Два различных корня
        x1 = (-b + sqrt(D)) / (2 * a);
        x2 = (-b - sqrt(D)) / (2 * a);
        printf("D > 0: Два корня\n");
        printf("x1 = %.2lf\n", x1);
        printf("x2 = %.2lf\n", x2);
    }
    else if (D == 0) {
        // Один корень (два совпадающих)
        x1 = -b / (2 * a);
        printf("D = 0: Один корень\n");
        printf("x1 = x2 = %.2lf\n", x1);
    }
    else {
        // D < 0, корней нет (в области действительных чисел)
        printf("D < 0: Действительных корней нет.\n");
    }

    return 0;
}


